def send_part(io, data):
    """Send one input part, then pause so the target's *next* read call is
    the one that consumes the following part.

    Without this pause a buffered-stdio reader (scanf/fgets) fills its
    4096-byte FILE buffer from the pipe in one go and a subsequent raw
    read(0, ...) sees EOF - the exploit then silently does nothing.
    """
    io.send(data)
    time.sleep(SETTLE)


