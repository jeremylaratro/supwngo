def _site(hit) -> str:
    return f"{hit.path}:{hit.line} [{hit.cls}/{hit.kind}] {hit.text}"


def match_hits(hits: Sequence, entries: Sequence[dict]) -> Tuple[list, list]:
    """Pair current hits with baseline entries.

    Returns ``(unmatched_hits, unmatched_entries)``.

    A hit matches the entry with the same ``(path, line, class, kind)``. A hit
    that has moved (an unrelated edit above it shifted its line) still matches
    an entry with the same ``(path, class, kind, anchor)``, where the anchor is
    the hash of its normalised source line; equal anchors in one file are paired
    in line order. A hit that both moved and had its own line rewritten matches
    nothing: its entry goes stale and the hit is unclassified, so the change has
    to be accounted for explicitly.
    """
    by_key: Dict[Tuple[str, int, str, str], dict] = {
        (e["path"], e["line"], e["class"], e["kind"]): e for e in entries
    }
    taken: set = set()
    leftover_hits = []
    for hit in hits:
        entry = by_key.get((hit.path, hit.line, hit.cls, hit.kind))
        if entry is None:
            leftover_hits.append(hit)
        else:
            taken.add(entry["id"])
    free_entries: Dict[Tuple[str, str, str, str], List[dict]] = defaultdict(list)
    for entry in entries:
        if entry["id"] not in taken:
            key = (entry["path"], entry["class"], entry["kind"], entry["anchor"])
            free_entries[key].append(entry)
    for queue in free_entries.values():
        queue.sort(key=lambda e: e["line"])
    unmatched_hits = []
    for hit in sorted(leftover_hits, key=lambda h: h.line):
        queue = free_entries.get((hit.path, hit.cls, hit.kind, hit.anchor))
        if queue:
            taken.add(queue.pop(0)["id"])
        else:
            unmatched_hits.append(hit)
    unmatched_entries = [e for e in entries if e["id"] not in taken]
    return unmatched_hits, unmatched_entries


def check_lifecycle(frozen: dict, current: dict) -> List[str]:
    """Violations of the frozen-fields and one-way-status rules.

    ``frozen`` is the baseline as committed at W-0, ``current`` the baseline now.
    """
    problems: List[str] = []
    old = {e["id"]: e for e in frozen["entries"]}
    new = {e["id"]: e for e in current["entries"]}
    for entry_id in sorted(old.keys() - new.keys()):
        problems.append(f"{entry_id}: entry deleted")
    for entry_id in sorted(new.keys() - old.keys()):
        problems.append(f"{entry_id}: entry added after W-0")
    for entry_id in sorted(old.keys() & new.keys()):
        before, after = old[entry_id], new[entry_id]
        for field in FROZEN_FIELDS:
            if before[field] != after[field]:
                problems.append(
                    f"{entry_id}: frozen field {field!r} changed "
                    f"{before[field]!r} -> {after[field]!r}"
                )
        if before["status"] in CLOSED and after["status"] != before["status"]:
            problems.append(
                f"{entry_id}: closed entry changed status "
                f"{before['status']} -> {after['status']}"
            )
        if after["status"] not in (OPEN, *CLOSED):
            problems.append(f"{entry_id}: unknown status {after['status']!r}")
    return problems


