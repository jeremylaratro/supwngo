def _entry(i, status="open", **extra):
    entry = {
        "id": audit.entry_id(i),
        "path": "supwngo/x.py",
        "line": i,
        "class": "A",
        "kind": "name_eq",
        "anchor": "0" * 10,
        "status": status,
    }
    entry.update(extra)
    return entry


def _bl(*entries):
    return {"entries": list(entries)}


def test_lifecycle_committed_baseline_agrees_with_itself(baseline):
    assert check_lifecycle(baseline, baseline) == []


def test_lifecycle_status_may_only_close(baseline):
    frozen = _bl(_entry(1), _entry(2), _entry(3))
    ok = _bl(
        _entry(1, "migrated", phase="W-3"),
        _entry(2, "allowed", justification="libc ABI"),
        _entry(3),
    )
    assert check_lifecycle(frozen, ok) == []
    reopened = _bl(_entry(1, "open"), _entry(2), _entry(3))
    closed = _bl(_entry(1, "migrated", phase="W-3"), _entry(2), _entry(3))
    assert check_lifecycle(closed, reopened), "migrated -> open must fail"
    swapped = _bl(_entry(1, "allowed", justification="x"), _entry(2), _entry(3))
    assert check_lifecycle(closed, swapped), "migrated -> allowed must fail"
    assert check_lifecycle(frozen, _bl(_entry(1, "bogus"), _entry(2), _entry(3)))


def test_lifecycle_entry_set_is_frozen():
    frozen = _bl(_entry(1), _entry(2))
    assert check_lifecycle(frozen, _bl(_entry(1))), "deleting an entry must fail"
    assert check_lifecycle(
        frozen, _bl(_entry(1), _entry(2), _entry(3))
    ), "adding an entry must fail"


@pytest.mark.parametrize(
    "field,value",
    [("path", "supwngo/y.py"), ("line", 99), ("class", "C"), ("kind", "x")],
)
def test_lifecycle_frozen_fields_cannot_change(field, value):
    frozen = _bl(_entry(1), _entry(2))
    changed = _bl(_entry(1, **{field: value}), _entry(2))
    problems = check_lifecycle(frozen, changed)
    assert problems and field in problems[0]


