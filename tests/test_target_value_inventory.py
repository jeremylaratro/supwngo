def test_scan_is_unique_and_in_canonical_order(hits):
    assert len({h.key for h in hits}) == len(hits), "duplicate hit keys"
    assert hits == sorted(hits, key=audit._sort_key)


def test_scanner_is_deterministic_in_process():
    """Same source, same hits, however many times and in whatever order."""
    sample = [
        REPO_ROOT / "supwngo" / rel
        for rel in (
            "exploit/pipeline/executors/offbyone_techniques.py",
            "exploit/pipeline/executors/fmtstr_techniques.py",
            "exploit/pipeline/executors/heap_and_bypass.py",
            "exploit/tester.py",
        )
    ]
    sources = [
        (f.relative_to(REPO_ROOT).as_posix(), f.read_text("utf-8")) for f in sample
    ]
    first = [audit.scan_source(src, path) for path, src in sources]
    second = [audit.scan_source(src, path) for path, src in reversed(sources)]
    assert first == list(reversed(second))
    assert any(first), "the sample produced no hits"


def test_scanner_output_does_not_depend_on_hash_seed(tmp_path):
    """Set iteration order must never leak into the hit list."""
    tree = tmp_path / "tree"
    pkg = tree / "supwngo"
    pkg.mkdir(parents=True)
    for rel in (
        "exploit/pipeline/executors/offbyone_techniques.py",
        "exploit/pipeline/executors/heap_and_bypass.py",
        "exploit/tester.py",
        "exploit/chainer.py",
    ):
        target = pkg / Path(rel).name
        shutil.copy(REPO_ROOT / "supwngo" / rel, target)
    outputs = []
    for seed in ("1", "2", "3"):
        env = dict(os.environ, PYTHONHASHSEED=seed)
        done = subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(tree)],
            env=env,
            capture_output=True,
            text=True,
            check=True,
            timeout=120,
        )
        outputs.append(done.stdout)
    assert json.loads(outputs[0])["hits"], "the sample produced no hits"
    assert outputs[0] == outputs[1] == outputs[2]
