def test_every_current_hit_has_a_baseline_entry(hits, baseline):
    unmatched, _ = match_hits(hits, baseline["entries"])
    assert not unmatched, (
        f"{len(unmatched)} current hit(s) have no entry in "
        f"tests/data/target_values_baseline.json. Each is a target-specific "
        f"value the product depends on and must be classified, not ignored. "
        f"After W-0 the baseline is frozen: remove the dependence (the plan's "
        f"single payoff API), do not add an entry.\n  "
        + "\n  ".join(_site(h) for h in unmatched)
    )


def test_no_stale_open_baseline_entry(hits, baseline):
    _, unmatched = match_hits(hits, baseline["entries"])
    stale = [e for e in unmatched if e["status"] == OPEN]
    assert not stale, (
        f"{len(stale)} `open` baseline entr(ies) match no current hit. The "
        f"site was removed or rewritten: close the entry explicitly "
        f"(status `migrated` with its phase, or `allowed` with a "
        f"justification); do not delete it.\n  "
        + "\n  ".join(
            f"{e['id']} {e['path']}:{e['line']} [{e['class']}/{e['kind']}]"
            for e in stale
        )
    )


def test_every_baseline_entry_is_well_formed(baseline):
    entries = baseline["entries"]
    assert entries, "the baseline is empty"
    problems: List[str] = []
    seen_ids: set = set()
    for entry in entries:
        label = f"{entry.get('id')} {entry.get('path')}:{entry.get('line')}"
        for field in (*FROZEN_FIELDS, "anchor", "status"):
            if field not in entry:
                problems.append(f"{label}: missing field {field!r}")
        if problems and problems[-1].startswith(label):
            continue
        if not ID_RE.match(entry["id"]):
            problems.append(f"{label}: id is not W-NNNN")
        if entry["id"] in seen_ids:
            problems.append(f"{label}: duplicate id")
        seen_ids.add(entry["id"])
        if entry["class"] not in audit.CLASSES:
            problems.append(f"{label}: class {entry['class']!r} is not a real class")
        elif audit.KIND_CLASS.get(entry["kind"]) != entry["class"]:
            problems.append(
                f"{label}: kind {entry['kind']!r} does not belong to class "
                f"{entry['class']!r}"
            )
        if not (isinstance(entry["line"], int) and entry["line"] >= 1):
            problems.append(f"{label}: line is not a positive integer")
        if not (entry["path"].startswith("supwngo/") and entry["path"].endswith(".py")):
            problems.append(f"{label}: path is outside supwngo/**/*.py")
        if entry["status"] == "migrated" and not entry.get("phase"):
            problems.append(f"{label}: `migrated` needs the closing `phase`")
        if entry["status"] == "allowed" and not entry.get("justification"):
            problems.append(f"{label}: `allowed` needs a `justification`")
        if entry["status"] not in (OPEN, *CLOSED):
            problems.append(f"{label}: unknown status {entry['status']!r}")
    assert not problems, "\n  ".join(["malformed baseline entries:", *problems])


def test_baseline_ids_are_sequential_in_scan_order(baseline):
    """The ID scheme: W-NNNN in (path, line, kind, class) order, from 1."""
    entries = baseline["entries"]
    order = sorted(entries, key=lambda e: (e["path"], e["line"], e["kind"], e["class"]))
    assert [e["id"] for e in entries] == [
        audit.entry_id(i + 1) for i in range(len(entries))
    ]
    assert entries == order, "entries are not in (path, line, kind, class) order"
    assert baseline["id_scheme"].startswith("W-NNNN")


def test_baseline_header_is_consistent(baseline):
    assert re.fullmatch(r"[0-9a-f]{40}", baseline["generated_at_commit"])
    assert baseline["counts"] == audit.counts(
        [
            audit.Hit(e["path"], e["line"], e["class"], e["kind"], "", "")
            for e in baseline["entries"]
        ]
    ), "counts disagree with entries; counts are written by --regen only"
    assert set(baseline["counts"]) == {*audit.CLASSES, "total"}


def test_every_current_hit_has_a_real_class_and_kind(hits):
    assert hits, "the scan found nothing: the scanner is broken"
    for hit in hits:
        assert hit.cls in audit.CLASSES, _site(hit)
        assert audit.KIND_CLASS[hit.kind] == hit.cls, _site(hit)
        assert hit.path.startswith("supwngo/") and hit.line >= 1, _site(hit)


