def test_match_exact_then_anchor_then_unmatched():
    Hit = audit.Hit
    entries = [
        dict(_entry(1), line=10, anchor="aaaa"),
        dict(_entry(2), line=20, anchor="bbbb"),
        dict(_entry(3), line=30, anchor="cccc"),
    ]
    exact = Hit("supwngo/x.py", 10, "A", "name_eq", "aaaa", "")
    shifted = Hit("supwngo/x.py", 25, "A", "name_eq", "bbbb", "")  # moved down 5
    edited = Hit("supwngo/x.py", 35, "A", "name_eq", "dddd", "")  # moved and rewritten
    new = Hit("supwngo/x.py", 40, "A", "name_eq", "eeee", "")
    unmatched_hits, unmatched_entries = match_hits(
        [exact, shifted, edited, new], entries
    )
    assert unmatched_hits == [edited, new]
    assert [e["id"] for e in unmatched_entries] == ["W-0003"]


def test_match_pairs_duplicate_lines_one_to_one():
    Hit = audit.Hit
    entries = [dict(_entry(i), line=10 * i, anchor="same") for i in (1, 2)]
    two = [Hit("supwngo/x.py", 11 * i, "A", "name_eq", "same", "") for i in (1, 2)]
    assert match_hits(two, entries) == ([], [])
    unmatched_hits, _ = match_hits(
        two + [Hit("supwngo/x.py", 99, "A", "name_eq", "same", "")], entries
    )
    assert len(unmatched_hits) == 1, "a third copy of a line is a new site"


