"""Directive W, phase W-0: the target-value inventory ratchet.

Plan: ``docs/plans/2026-11-13-retire-hardcoded-target-values-plan.md`` section 2.

``scripts/audit_target_values.py`` is a pinned AST scan of ``supwngo/**/*.py``
for every site where the product depends on a target's own values: payoff names
(class A, and A' inside generated-script templates), guessed integer candidates
(B), and success or flag-pattern strings (C). The scan is run on every test run.
``tests/data/target_values_baseline.json`` is the same scan frozen once at the
W-0 merge base; its entries are the denominator of directive W.

Red at W-0 (this module):

* a current hit with no baseline entry fails, naming the site;
* a baseline entry whose class or kind is not real fails;
* an ``open`` baseline entry that no current hit matches is stale and fails.
  Closed (``migrated`` / ``allowed``) tombstones are exempt.

Lifecycle of the baseline file (plan section 2): after W-0 the entry set and
each entry's ``id``, ``path``, ``line`` and ``class`` never change. The one
mutable field is ``status``, and it only moves ``open`` -> ``migrated`` or
``allowed``, never back. ``check_lifecycle`` below is that rule, tested here on
synthetic inputs; the real check against the W-0 commit's copy is a TODO.

The file is generated by ``python3 -I scripts/audit_target_values.py --regen``,
at the W-0 merge base only. It is never regenerated and never edited by hand
apart from an entry's closure status.

Pure Python: no binary, no network, no subprocess beyond one tiny scan.
"""

